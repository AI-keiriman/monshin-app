def seed_price_rules() -> None:
    """料金表を入れる。同じ code があれば、作り直さずに値を更新する"""
    for code, label, symptom_example, min_price, max_price in PRICE_RULES:
        rule = db.session.scalar(db.select(PriceRule).filter_by(code=code))
        if rule is None:
            rule = PriceRule(code=code)
            db.session.add(rule)
        rule.label = label
        rule.symptom_example = symptom_example
        rule.min_price = min_price
        rule.max_price = max_price
    db.session.commit()


def seed_diagnosis_guides() -> None:
    """診断の手引きを入れる。同じ code があれば、作り直さずに値を更新する"""
    for code, symptom, causes, checks, how_to_tell, category_code in DIAGNOSIS_GUIDES:
        guide = db.session.scalar(db.select(DiagnosisGuide).filter_by(code=code))
        if guide is None:
            guide = DiagnosisGuide(code=code)
            db.session.add(guide)
        guide.symptom = symptom
        guide.causes = causes
        guide.checks = checks
        guide.how_to_tell = how_to_tell
        guide.category_code = category_code
    db.session.commit()


def init_app(app):
    @app.cli.command("seed")
    def seed():
        """料金表と診断の手引きの初期データを入れる。何度実行してもよい（既存の行は更新する）"""
        seed_price_rules()
        click.echo(f"料金表を{len(PRICE_RULES)}件、入れました")
        seed_diagnosis_guides()
        click.echo(f"診断の手引きを{len(DIAGNOSIS_GUIDES)}件、入れました")
